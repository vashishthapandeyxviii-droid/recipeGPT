-- RecipeGPT schema (PostgreSQL 18). Safe to run more than once.

-- 1) One row per recipe: the facts that appear exactly once per recipe.
CREATE TABLE IF NOT EXISTS recipes (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 TEXT    NOT NULL UNIQUE,
    category             TEXT    NOT NULL CHECK (category IN
                           ('breakfast','main','side','soup','snack','salad','dessert')),
    difficulty           TEXT    NOT NULL CHECK (difficulty IN ('easy','medium','hard')),
    cooking_time_minutes INTEGER NOT NULL CHECK (cooking_time_minutes > 0),
    servings             INTEGER NOT NULL CHECK (servings > 0)
);

-- 2) One row per distinct ingredient ("potato" is stored once, not once per recipe).
CREATE TABLE IF NOT EXISTS ingredients (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT    NOT NULL UNIQUE CHECK (name = lower(name))
);

-- 3) The link between recipes and ingredients. Quantity/unit/note live HERE because
--    they describe "how much potato in THIS recipe", not potato in general.
CREATE TABLE IF NOT EXISTS recipe_ingredients (
    recipe_id     INTEGER  NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    ingredient_id INTEGER  NOT NULL REFERENCES ingredients(id),
    position      SMALLINT NOT NULL CHECK (position > 0),
    quantity      NUMERIC(8,2) CHECK (quantity IS NULL OR quantity > 0),
    unit          TEXT,
    note          TEXT,
    PRIMARY KEY (recipe_id, ingredient_id)
);

-- Makes "which recipes use ingredient X?" fast.
CREATE INDEX IF NOT EXISTS idx_recipe_ingredients_ingredient
    ON recipe_ingredients (ingredient_id);

-- 4) Cooking steps, one row per step, in order.
CREATE TABLE IF NOT EXISTS recipe_steps (
    recipe_id   INTEGER  NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    step_number SMALLINT NOT NULL CHECK (step_number > 0),
    instruction TEXT     NOT NULL,
    PRIMARY KEY (recipe_id, step_number)
);

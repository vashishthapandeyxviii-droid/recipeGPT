-- RecipeGPT chat tables (PostgreSQL 18). Safe to run more than once.
-- Does NOT touch the recipe tables.

-- 1) One row per saved conversation (what the sidebar lists).
CREATE TABLE IF NOT EXISTS conversations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      TEXT NOT NULL DEFAULT 'New chat' CHECK (length(trim(title)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 2) Every message in every conversation.
--    focus_recipe_id = the recipe this reply explained in detail (so "it" can be resolved later).
CREATE TABLE IF NOT EXISTS messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    role            TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
    content         TEXT NOT NULL CHECK (length(trim(content)) > 0),
    ai_used         BOOLEAN NOT NULL DEFAULT FALSE,
    focus_recipe_id INTEGER REFERENCES recipes(id) ON DELETE SET NULL,
    show_recipe     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Added in Stage 5: should the page draw the focus recipe as a full card? (existing databases get it here)
ALTER TABLE messages ADD COLUMN IF NOT EXISTS show_recipe BOOLEAN NOT NULL DEFAULT FALSE;

-- 3) Which recipes an assistant message suggested, in order.
--    This is how "the second one" is understood: position 2 of the latest suggestion list.
CREATE TABLE IF NOT EXISTS message_recipes (
    message_id BIGINT   NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    recipe_id  INTEGER  NOT NULL REFERENCES recipes(id),
    position   SMALLINT NOT NULL CHECK (position > 0),
    PRIMARY KEY (message_id, recipe_id),
    UNIQUE (message_id, position)
);

-- Fast loading of a conversation's messages and of the sidebar list.
CREATE INDEX IF NOT EXISTS idx_messages_conversation ON messages (conversation_id, id);
CREATE INDEX IF NOT EXISTS idx_conversations_updated ON conversations (updated_at DESC);
